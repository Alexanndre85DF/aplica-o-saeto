def ensure_colunas(conn) -> None:
    if USAR_POSTGRES and DATABASE_URL:
        _ensure_colunas_postgres(conn)
        return
    cols = {row[1] for row in conn.execute("PRAGMA table_info(aplicadores)")}
    if "cpf" not in cols:
        conn.execute("ALTER TABLE aplicadores ADD COLUMN cpf TEXT")
    if "numero" not in cols:
        conn.execute("ALTER TABLE aplicadores ADD COLUMN numero INTEGER")
    if "acesso_token" not in cols:
        conn.execute("ALTER TABLE aplicadores ADD COLUMN acesso_token TEXT")
    conn.execute(
        """CREATE TABLE IF NOT EXISTS sessoes_acesso (
            token TEXT PRIMARY KEY,
            aplicador_id INTEGER NOT NULL REFERENCES aplicadores(id),
            criado_em TEXT NOT NULL,
            expira_em TEXT NOT NULL
        )"""
    )
    for row in conn.execute("SELECT id, codigo, numero FROM aplicadores"):
        codigo = row["codigo"] or ""
        m = re.search(r"(\d+)", codigo)
        if not m:
            continue
        n = int(m.group(1))
        if row["numero"] != n:
            conn.execute("UPDATE aplicadores SET numero = ? WHERE id = ?", (n, row["id"]))
    vcols = {row[1] for row in conn.execute("PRAGMA table_info(vagas)")}
    if "finalizado_em" not in vcols:
        conn.execute("ALTER TABLE vagas ADD COLUMN finalizado_em TEXT")
    if "turma" not in vcols:
        conn.execute("ALTER TABLE vagas ADD COLUMN turma TEXT")
    if "n_alunos" not in vcols:
        conn.execute("ALTER TABLE vagas ADD COLUMN n_alunos INTEGER")
    if not USAR_POSTGRES:
        _permitir_vaga_sem_data(conn)
    vcols = {row[1] for row in conn.execute("PRAGMA table_info(vagas)")}
    if "alocacao" not in vcols:
        conn.execute("ALTER TABLE vagas ADD COLUMN alocacao TEXT")
    try:
        vicols = {row[1] for row in conn.execute("PRAGMA table_info(viagens)")}
        if "dias_aplicacao" not in vicols:
            conn.execute("ALTER TABLE viagens ADD COLUMN dias_aplicacao TEXT")
    except Exception:
        pass


def init_db() -> None:
    conn = connect()
    try:
        if USAR_POSTGRES and DATABASE_URL:
            conn.executescript(PG_SCHEMA)
            conn.execute(
                "INSERT OR REPLACE INTO meta(chave, valor) VALUES (?, ?)",
                ("schema", SCHEMA_VERSION),
            )
            ensure_colunas(conn)
        else:
            conn.execute(
                "CREATE TABLE IF NOT EXISTS meta (chave TEXT PRIMARY KEY, valor TEXT)"
            )
            conn.executescript(SQLITE_SCHEMA)
            conn.execute(
                "INSERT OR REPLACE INTO meta(chave, valor) VALUES (?, ?)",
                ("schema", SCHEMA_VERSION),
            )
            ensure_colunas(conn)
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()
    if USAR_POSTGRES and DATABASE_URL:
        _migrar_sqlite_se_postgres_vazio()
    elif usando_nuvem():
        try:
            _migrar_sqlite_se_nuvem_vazia()
        except Exception as exc:
            print("Aviso: ainda não gravou no Supabase.", exc)
    conn = connect()
    try:
        _limpar_datas_inventadas(conn)
        conn.commit()
    finally:
        conn.close()


