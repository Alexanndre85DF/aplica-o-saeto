def _tabelas_sqlite(src: sqlite3.Connection) -> set[str]:
    return {
        r[0]
        for r in src.execute(
            "SELECT name FROM sqlite_master WHERE type='table'"
        )
    }


def _colunas_sqlite(src: sqlite3.Connection, tabela: str) -> list[str]:
    return [row[1] for row in src.execute(f"PRAGMA table_info({tabela})")]


def _copiar_tabela(src: sqlite3.Connection, dest, tabela: str, colunas: list[str]) -> None:
    existentes = _colunas_sqlite(src, tabela)
    usar = [c for c in colunas if c in existentes]
    if not usar:
        return
    rows = src.execute(f"SELECT {', '.join(usar)} FROM {tabela}").fetchall()
    if not rows:
        return
    ph = ", ".join("?" for _ in usar)
    cols = ", ".join(usar)
    for r in rows:
        dest.execute(
            f"INSERT INTO {tabela} ({cols}) VALUES ({ph})",
            tuple(r[c] for c in usar),
        )


def _ajustar_sequencia(dest, tabela: str) -> None:
    if tabela not in _TABELAS_COM_ID:
        return
    max_id = dest.execute(f"SELECT COALESCE(MAX(id), 0) n FROM {tabela}").fetchone()["n"]
    if not max_id:
        return
    dest.execute(
        "SELECT setval(pg_get_serial_sequence(%s, 'id'), %s, true)",
        (tabela, int(max_id)),
    )


def _migrar_sqlite_se_postgres_vazio() -> None:
    if not DB_PATH.exists():
        return
    with get_db() as pg:
        n = pg.execute("SELECT COUNT(*) n FROM municipios").fetchone()["n"]
        if n:
            return
    src = sqlite3.connect(DB_PATH)
    src.row_factory = sqlite3.Row
    try:
        tabelas = _tabelas_sqlite(src)
        if "municipios" not in tabelas:
            return
        nsrc = src.execute("SELECT COUNT(*) FROM municipios").fetchone()[0]
        if not nsrc:
            return
        with get_db() as pg:
            _copiar_tabela(src, pg, "municipios", ["id", "nome"])
            if "escolas" in tabelas:
                _copiar_tabela(
                    src,
                    pg,
                    "escolas",
                    ["id", "codigo", "nome", "municipio_id", "rede", "rural"],
                )
            if "aplicadores" in tabelas:
                _copiar_tabela(
                    src,
                    pg,
                    "aplicadores",
                    ["id", "codigo", "nome", "cpf", "numero", "acesso_token", "ativo"],
                )
            if "viagens" in tabelas:
                _copiar_tabela(
                    src,
                    pg,
                    "viagens",
                    ["id", "municipio_id", "data_saida", "data_retorno", "dias_aplicacao"],
                )
            if "vagas" in tabelas:
                _copiar_tabela(
                    src,
                    pg,
                    "vagas",
                    [
                        "id",
                        "escola_id",
                        "serie",
                        "turno",
                        "data",
                        "ordem",
                        "origem_linha",
                        "aplicador_id",
                        "status",
                        "finalizado_em",
                        "turma",
                        "n_alunos",
                        "alocacao",
                    ],
                )
            if "sessoes_acesso" in tabelas:
                _copiar_tabela(
                    src,
                    pg,
                    "sessoes_acesso",
                    ["token", "aplicador_id", "criado_em", "expira_em"],
                )
            if "meta" in tabelas:
                _copiar_tabela(src, pg, "meta", ["chave", "valor"])
            for tabela in ("municipios", "escolas", "aplicadores", "viagens", "vagas"):
                if tabela in tabelas:
                    _ajustar_sequencia(pg, tabela)
    finally:
        src.close()


def row_to_dict(row) -> dict | None:
    if row is None:
        return None
    if isinstance(row, dict):
        return dict(row)
    return {k: row[k] for k in row.keys()}


def rows_to_dicts(rows) -> list[dict]:
    return [row_to_dict(r) for r in rows]


