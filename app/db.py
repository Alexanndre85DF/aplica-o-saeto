class Row(dict):
    """Linha que aceita row['col'], row[0] e dict(row), como o sqlite3.Row."""

    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


class PgCursor:
    def __init__(self, inner):
        self._inner = inner
        self._rows: list[Row] = []
        self._i = 0
        self.lastrowid = None

    def execute(self, sql: str, params=()):
        raw = sql.strip()
        if raw.upper().startswith("PRAGMA"):
            return self._pragma(raw)
        sql_pg = _adaptar_sql(raw)
        args = None if params is None or params == () else tuple(params)
        self._inner.execute(sql_pg, args)
        self.lastrowid = None
        self._i = 0
        if self._inner.description:
            names = [d.name for d in self._inner.description]
            fetched = self._inner.fetchall()
            self._rows = [Row({k: _valor_pg(v) for k, v in zip(names, rec)}) for rec in fetched]
            if self._rows and "id" in self._rows[0]:
                self.lastrowid = self._rows[0]["id"]
        else:
            self._rows = []
        return self

    def _pragma(self, sql: str):
        self.lastrowid = None
        self._i = 0
        self._rows = []
        m = re.match(r"PRAGMA\s+table_info\(\s*[\"']?(\w+)[\"']?\s*\)", sql, re.I)
        if not m:
            return self
        tabela = m.group(1).lower()
        self._inner.execute(
            """SELECT column_name FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = %s
               ORDER BY ordinal_position""",
            (tabela,),
        )
        self._rows = [_PragmaRow(i, r[0]) for i, r in enumerate(self._inner.fetchall())]
        return self

    def fetchone(self):
        if self._i >= len(self._rows):
            return None
        row = self._rows[self._i]
        self._i += 1
        return row

    def fetchall(self):
        rest = self._rows[self._i :]
        self._i = len(self._rows)
        return rest

    def __iter__(self):
        return iter(self.fetchall())


class _PragmaRow:
    def __init__(self, cid: int, name: str):
        self._vals = (cid, name)

    def __getitem__(self, key):
        if key in (0, "cid"):
            return self._vals[0]
        if key in (1, "name"):
            return self._vals[1]
        raise KeyError(key)

    def keys(self):
        return ("cid", "name")


class PgConnection:
    def __init__(self, inner):
        self._inner = inner
        self._cursor = None

    def execute(self, sql: str, params=()):
        if self._cursor is None:
            self._cursor = self._inner.cursor()
        return PgCursor(self._cursor).execute(sql, params)

    def executescript(self, script: str) -> None:
        for stmt in _partir_sql(script):
            if stmt.upper().startswith("PRAGMA"):
                continue
            self.execute(stmt)

    def commit(self) -> None:
        self._inner.commit()

    def rollback(self) -> None:
        self._inner.rollback()

    def close(self) -> None:
        self._inner.close()


def _valor_pg(valor):
    if isinstance(valor, Decimal):
        return int(valor) if valor % 1 == 0 else float(valor)
    return valor


def _partir_sql(script: str) -> list[str]:
    partes = []
    for raw in script.split(";"):
        stmt = raw.strip()
        if stmt:
            partes.append(stmt)
    return partes


def _adaptar_sql(sql: str) -> str:
    sql = sql.strip().rstrip(";")
    m_ignore = re.match(r"INSERT\s+OR\s+IGNORE\s+INTO\s+(\w+)", sql, re.I)
    m_replace = re.match(r"INSERT\s+OR\s+REPLACE\s+INTO\s+(\w+)", sql, re.I)
    if m_ignore:
        tabela = m_ignore.group(1).lower()
        sql = re.sub(r"INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", sql, count=1, flags=re.I)
        col = _CONFLITO.get(tabela)
        if col and "ON CONFLICT" not in sql.upper():
            sql += f" ON CONFLICT ({col}) DO NOTHING"
    elif m_replace:
        tabela = m_replace.group(1).lower()
        sql = re.sub(r"INSERT\s+OR\s+REPLACE\s+INTO", "INSERT INTO", sql, count=1, flags=re.I)
        col = _CONFLITO.get(tabela, "chave")
        cols = _colunas_insert(sql)
        sets = ", ".join(f"{c}=EXCLUDED.{c}" for c in cols if c.lower() != col.lower())
        if "ON CONFLICT" not in sql.upper():
            sql += f" ON CONFLICT ({col}) DO UPDATE SET {sets or f'{col}=EXCLUDED.{col}'}"
    sql = re.sub(r"ON CONFLICT\s*\(", "ON CONFLICT (", sql, flags=re.I)
    sql = _trocar_placeholders(sql)
    if _precisa_returning(sql):
        sql += " RETURNING id"
    return sql


def _colunas_insert(sql: str) -> list[str]:
    m = re.search(r"INSERT\s+INTO\s+\w+\s*\(([^)]+)\)", sql, re.I)
    if not m:
        return []
    return [c.strip() for c in m.group(1).split(",") if c.strip()]


def _precisa_returning(sql: str) -> bool:
    upper = sql.upper()
    if not upper.startswith("INSERT") or "RETURNING" in upper:
        return False
    m = re.search(r"INSERT\s+INTO\s+(\w+)", sql, re.I)
    if not m:
        return False
    return m.group(1).lower() in _TABELAS_COM_ID


def _trocar_placeholders(sql: str) -> str:
    out = []
    i = 0
    while i < len(sql):
        ch = sql[i]
        if ch == "?":
            out.append("%s")
        else:
            out.append(ch)
        i += 1
    return "".join(out)


def _url_postgres(url: str) -> str:
    from urllib.parse import parse_qsl, urlencode, urlparse, urlunparse

    if url.startswith("postgres://"):
        url = "postgresql://" + url[len("postgres://") :]
    parsed = urlparse(url)
    permitidos = {"sslmode", "connect_timeout", "options"}
    query = {k: v for k, v in parse_qsl(parsed.query) if k.lower() in permitidos}
    if "sslmode" not in {k.lower() for k in query}:
        query["sslmode"] = "require"
    limpa = parsed._replace(query=urlencode(query))
    return urlunparse(limpa)


def connect():
    if USAR_POSTGRES and DATABASE_URL:
        import psycopg
        from urllib.parse import urlparse

        url = _url_postgres(DATABASE_URL)
        parsed = urlparse(url)
        print("Postgres host:", parsed.hostname, "porta:", parsed.port)
        try:
            inner = psycopg.connect(
                url,
                autocommit=False,
                prepare_threshold=None,
                connect_timeout=30,
            )
        except Exception as exc:
            msg = str(exc).replace(parsed.password or "", "***") if parsed.password else str(exc)
            raise RuntimeError(
                "Não foi possível conectar ao Supabase. "
                f"Host {parsed.hostname} porta {parsed.port}. {msg}"
            ) from exc
        return PgConnection(inner)
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


@contextmanager
def get_db() -> Iterator[Any]:
    conn = connect()
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def _permitir_vaga_sem_data(conn) -> None:
    try:
        info = list(conn.execute("PRAGMA table_info(vagas)"))
    except Exception:
        return
    if not info:
        return
    data_col = next((r for r in info if r[1] == "data"), None)
    if data_col is not None and not data_col[3]:
        return
    existentes = [r[1] for r in info]
    destino = [
        "id",
        "escola_id",
        "serie",
        "turno",
        "data",
        "ordem",
        "origem_linha",
        "aplicador_id",
        "status",
        "finalizado_em",
        "turma",
        "n_alunos",
    ]
    comuns = [c for c in destino if c in existentes]
    conn.execute("PRAGMA foreign_keys = OFF")
    conn.execute(
        """CREATE TABLE vagas_data_opcional (
            id INTEGER PRIMARY KEY,
            escola_id INTEGER NOT NULL REFERENCES escolas(id),
            serie TEXT NOT NULL,
            turno TEXT NOT NULL,
            data TEXT,
            ordem INTEGER NOT NULL DEFAULT 1,
            origem_linha INTEGER UNIQUE,
            aplicador_id INTEGER REFERENCES aplicadores(id),
            status TEXT NOT NULL DEFAULT 'PREVISTA',
            finalizado_em TEXT,
            turma TEXT,
            n_alunos INTEGER
        )"""
    )
    conn.execute(
        f"INSERT INTO vagas_data_opcional ({', '.join(comuns)}) SELECT {', '.join(comuns)} FROM vagas"
    )
    conn.execute("DROP TABLE vagas")
    conn.execute("ALTER TABLE vagas_data_opcional RENAME TO vagas")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_vagas_data ON vagas(data)")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_vagas_aplicador ON vagas(aplicador_id)")
    conn.execute("PRAGMA foreign_keys = ON")


